'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const dash=require('../web/dashboard.js');
const source=process.argv[2];
if(!source)throw Error('Pass overview-fixtures.json generated by JdbcOverviewHttpTest');
const fixtures=JSON.parse(fs.readFileSync(source,'utf8'));let checks=0;
for(const [name,data] of Object.entries(fixtures)){
 if(name==='item')continue;
 const expected=data.summary.datasources;
 const id=data.scope.hostId;
 const html=id?dash.machine(data,id):dash.overview(data);
 assert.ok(expected>0);checks++;
 assert.equal(dash.count(data,'datasources'),expected);checks++;
 assert.equal(dash.datasourceSummary(data).configured,expected);checks++;
 assert.equal(dash.datasourceSummary(data).runtime,0);checks++;
 assert.match(html,/JDBC datasources/);checks++;
 assert.match(html,/data-inventory="libraries" data-subset="datasources"/);checks++;
 assert.match(html,new RegExp('>'+expected+'</strong>'));checks++;
 assert.ok(!html.includes('PRIVATE_'));checks++;
 if(id){
  assert.match(html,/Configuration found/);checks++;
  for(const row of data.datasources){assert.ok(html.includes(dash.esc(row.name)));checks++;}
 }
}
const result={status:'PASS',checks,input:path.resolve(source),scope:['global','environment','Tomcat machine','JBoss machine'],collectorGeneratedRows:true};
fs.writeFileSync(path.join(path.dirname(source),'jdbc-overview-render.json'),JSON.stringify(result,null,2)+'\n');
console.log('PASS: '+checks+' JDBC overview render checks on actual collector -> HTTP -> SQLite fixture data');
