assert(!dashboard.serverAssociation({...direct,serverId:'deleted'},serverA));
assert(!dashboard.serverAssociation({...direct,hostId:'other'},serverA));
assert(dashboard.serverAssociation({hostId:'h',serverName:'AdminServer',pid:7},serverA));
