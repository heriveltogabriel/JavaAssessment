'use strict';
const assert=require('node:assert/strict');
const dashboard=require('../web/dashboard.js');
const row={id:'ds',hostId:'h',name:'Orders',state:'CONFIGURED',databaseHost:'rac-a',databasePort:1521,databaseName:'orders',databaseEndpoints:[{host:'rac-a',port:1521,password:'NEVER_RENDER'},{host:'rac-b',port:1522},{host:'2001:db8::7',port:1523},{host:'rac-b',port:1522}],url:'jdbc:secret'};
assert.equal(dashboard.databaseDestination(row),'rac-a:1521, rac-b:1522, [2001:db8::7]:1523 / orders');
assert.equal(dashboard.databaseEndpoints(row).length,3);
assert.equal(dashboard.databaseDestination({databaseHost:'old.example',databasePort:5432,databaseName:'billing'}),'old.example:5432 / billing');
assert.equal(dashboard.databaseDestination({}), '');
assert.equal(dashboard.databaseDestination({databaseName:'local-memory'}),'local-memory');
assert.equal(dashboard.databaseDestination({databaseEndpoints:[null,'bad',{host:{password:'NEVER_RENDER'},port:1521}]}),'');
const data={hosts:[{id:'h',hostname:'test-host'}],datasources:[row],runtimes:[],applications:[],libraries:[],servers:[],jobs:[]};
const html=dashboard.machine(data,'h');
assert(html.includes('Destino configurado'));
assert(html.includes('rac-b:1522'));
assert(!html.includes('NEVER_RENDER')&&!html.includes('jdbc:secret'));
row.databaseEndpoints=[{host:'<img src=x onerror=alert(1)>',port:1521}];
assert(!dashboard.machine(data,'h').includes('<img src=x'));
assert(dashboard.machine(data,'h').includes('&lt;img'));
console.log('JDBC_ENDPOINT_UI_TESTS=PASS multi-endpoint IPv6 legacy absent malformed deduplication destination rendering escaping');

