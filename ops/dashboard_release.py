"""Reserve dashboard release numbers locally; never publish or contact a host."""
import datetime
import fcntl
import json
import os
from pathlib import Path
import re
import tempfile


def version_numbers(value):
    if value == '1.0-beta':
        value = '1.0.0-beta'
    match = re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-beta)?', value)
    if not match:
        raise ValueError('Invalid dashboard release version')
    return tuple(map(int, match.groups()))


def next_version(value):
    major, minor, patch = version_numbers(value)
    return f'{major}.{minor}.{patch + 1}'


def agent_version(source):
    values = re.findall(r'\bstatic final String VERSION = "([^"]+)";', source)
    if len(values) != 1:
        raise ValueError('Expected exactly one agent version constant')
    version_numbers(values[0])
    return values[0]


def agent_source(source, version):
    version_numbers(version)
    old = agent_version(source)
    return source.replace('static final String VERSION = "' + old + '";',
                          'static final String VERSION = "' + version + '";')


def java_source(release):
    next_version(release['version'])  # Validate before generating source.
    timestamp = datetime.datetime.fromisoformat(release['builtAt'])
    if timestamp.tzinfo is None:
        raise ValueError('Release timestamp requires timezone')
    return ('package assessment;\n\n'
            '/** Generated by ops/build-dashboard-release.py. Prepare a new release to increment. */\n'
            'public final class DashboardVersion {\n'
            f'    public static final String VERSION = {json.dumps(release["version"])};\n'
            f'    public static final String BUILT_AT = {json.dumps(release["builtAt"])};\n'
            '    private DashboardVersion() {}\n}\n')


def stable_version(value):
    """Explicit releases use complete, stable SemVer; legacy beta history remains readable."""
    if not isinstance(value, str) or not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', value):
        raise ValueError('Requested release must be a complete stable version, for example 2.0.0')
    version_numbers(value)
    return value


def write_state(state_path, state):
    """Replace the ledger atomically while the caller holds its release lock."""
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=state_path.parent,
                                         prefix='.dashboard-release-', suffix='.next', delete=False) as output:
            temporary = Path(output.name)
            output.write(json.dumps(state, indent=2) + '\n')
            output.flush()
            os.fsync(output.fileno())
        temporary.replace(state_path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def reserve(root, minimum_version=None, requested_version=None):
    root = Path(root)
    state_path = root / 'release/dashboard.json'
    lock_path = root / 'release/.dashboard-release.lock'
    state_path.parent.mkdir(parents=True, exist_ok=True)
    with lock_path.open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        state = json.loads(state_path.read_text())
        highest = max(version_numbers(state['version']), version_numbers(minimum_version or state['version']),
                      *(version_numbers(item['version']) for item in state['releases']))
        if requested_version is None:
            version = next_version('.'.join(map(str, highest)))
        else:
            version = stable_version(requested_version)
            if version_numbers(version) <= highest:
                raise ValueError('Requested release must be newer than every reserved dashboard and agent version')
        output = root / 'output/dashboard-releases' / version
        output.mkdir(parents=True, exist_ok=False)
        release = {'version': version, 'builtAt': datetime.datetime.now(datetime.timezone.utc).isoformat(),
                   'status': 'reserved'}
        state['version'] = version
        state['releases'].append(release)
        # A failed ledger write intentionally leaves this output directory reserved:
        # a later attempt must never reuse a potentially partial release.
        write_state(state_path, state)
    return release, output


def finish(root, version, status):
    root = Path(root)
    state_path = root / 'release/dashboard.json'
    with (state_path.parent / '.dashboard-release.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        state = json.loads(state_path.read_text())
        release = next(item for item in state['releases'] if item['version'] == version)
        release['status'] = status
        write_state(state_path, state)


def reserve_update_pair(root, minimum_version=None, requested_version=None):
    """Reserve B and T in one lock, without reusing an internal bridge number."""
    root = Path(root)
    state_path = root / 'release/dashboard.json'
    state_path.parent.mkdir(parents=True, exist_ok=True)
    with (state_path.parent / '.dashboard-release.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        state = json.loads(state_path.read_text())
        highest = max(version_numbers(state['version']), version_numbers(minimum_version or state['version']),
                      *(version_numbers(item['version']) for item in state['releases']))
        bridge = next_version('.'.join(map(str, highest)))
        target = next_version(bridge) if requested_version is None else stable_version(requested_version)
        if version_numbers(target) <= version_numbers(bridge):
            raise ValueError('Full update needs a reserved internal bridge below the final release')
        base = root / 'output/dashboard-releases'
        # A partial mkdir remains a used reservation; no existing output is reset.
        (base / bridge).mkdir(parents=True, exist_ok=False)
        output = base / target
        output.mkdir(parents=True, exist_ok=False)
        built_at = datetime.datetime.now(datetime.timezone.utc).isoformat()
        internal = {'version': bridge, 'builtAt': built_at, 'status': 'bridge-reserved',
                    'kind': 'agent-bridge', 'targetVersion': target}
        release = {'version': target, 'builtAt': built_at, 'status': 'reserved', 'bridgeVersion': bridge}
        state['version'] = target
        state['releases'].extend((internal, release))
        write_state(state_path, state)
        return release, output
